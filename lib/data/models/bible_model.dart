// lib/data/models/bible_model.dart
// ─────────────────────────────────────────────────────────────────────────────
// In-memory models for the parsed Bible XML.
// No Firestore — the Bible is loaded from bundled assets.
// ─────────────────────────────────────────────────────────────────────────────

class BibleVerse {
  const BibleVerse({required this.number, required this.text});
  final int    number;
  final String text;
}

class BibleChapter {
  const BibleChapter({required this.number, required this.verses});
  final int              number;
  final List<BibleVerse> verses;
}

class BibleBook {
  const BibleBook({
    required this.number,
    required this.testament,
    required this.nameAr,
    required this.nameEl,
    required this.chapters,
  });
  final int               number;
  final String            testament;  // 'Old' | 'New'
  final String            nameAr;
  final String            nameEl;
  final List<BibleChapter> chapters;

  int get chapterCount => chapters.length;
}

